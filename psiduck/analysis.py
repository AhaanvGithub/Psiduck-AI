"""Scoring, paired McNemar tests, SUMMARY.md and the README results block."""

from __future__ import annotations

import json
from math import comb
from pathlib import Path
from typing import Optional

CONFIG_ORDER = ("baseline", "latent", "latent-early-exit")
README_START = "<!-- RESULTS:START (generated by analyze.py from SUMMARY.md; do not edit) -->"
README_END = "<!-- RESULTS:END -->"


def read_jsonl(path: Path) -> dict[int, dict]:
    """idx -> record. Later lines win; a torn final line (crash mid-write) is ignored."""
    out: dict[int, dict] = {}
    if not path.exists():
        return out
    with path.open(encoding="utf-8") as f:
        for line in f:
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            out[int(r["idx"])] = r
    return out


def mcnemar_exact(b: int, c: int) -> float:
    """Exact two-sided McNemar p-value from the discordant counts b and c."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = 2 * sum(comb(n, i) for i in range(k + 1)) / 2**n
    return min(1.0, p)


def config_stats(recs: list[dict]) -> dict:
    n = len(recs)
    if n == 0:
        return dict(n=0)

    def mean(key):
        return sum(r.get(key, 0) or 0 for r in recs) / n

    return dict(
        n=n,
        correct=sum(bool(r.get("correct")) for r in recs),
        gen_tokens=mean("generated_tokens"),
        forward_passes=mean("forward_passes"),
        latent_steps=mean("latent_steps"),
        wall_s=mean("wall_s"),
        errors=sum(1 for r in recs if r.get("error")),
        cap_hits=sum(1 for r in recs if r.get("hit_token_cap")),
    )


def paired(a: dict[int, dict], b: dict[int, dict]) -> Optional[dict]:
    """Compare config a against config b on the problems both finished."""
    idx = sorted(set(a) & set(b))
    if not idx:
        return None
    both = sum(1 for i in idx if a[i]["correct"] and b[i]["correct"])
    a_only = sum(1 for i in idx if a[i]["correct"] and not b[i]["correct"])
    b_only = sum(1 for i in idx if not a[i]["correct"] and b[i]["correct"])
    neither = len(idx) - both - a_only - b_only
    tok_a = sum(a[i].get("generated_tokens", 0) for i in idx)
    tok_b = sum(b[i].get("generated_tokens", 0) for i in idx)
    fp_a = sum(a[i].get("forward_passes", 0) for i in idx)
    fp_b = sum(b[i].get("forward_passes", 0) for i in idx)
    return dict(
        n=len(idx), both=both, a_only=a_only, b_only=b_only, neither=neither,
        acc_diff=(a_only - b_only) / len(idx),
        p=mcnemar_exact(a_only, b_only),
        token_reduction=(1 - tok_a / tok_b) if tok_b else None,
        forward_ratio=(fp_a / fp_b) if fp_b else None,
    )


def load_results(results_dir: Path, dataset: str, n: Optional[int]) -> dict[str, dict[int, dict]]:
    out = {}
    for cfg in CONFIG_ORDER:
        recs = read_jsonl(results_dir / dataset / f"{cfg}.jsonl")
        if n is not None:
            recs = {i: r for i, r in recs.items() if i < n}
        if recs:
            out[cfg] = recs
    return out


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _p(p: float) -> str:
    return f"{p:.2g}" if p >= 1e-4 else f"{p:.1e}"


def dataset_section(title: str, results: dict[str, dict[int, dict]], expected_n: int) -> list[str]:
    lines = [f"## {title}", ""]
    if not results:
        return lines + ["_No results yet._", ""]
    lines += [
        "| config | correct | accuracy | mean generated tokens | mean forward passes | mean wall s/problem | errors | hit token cap |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for cfg, recs in results.items():
        s = config_stats(list(recs.values()))
        done = "" if s["n"] == expected_n else f" (incomplete: {s['n']}/{expected_n} run)"
        lines.append(
            f"| {cfg}{done} | {s['correct']}/{s['n']} | {_pct(s['correct'] / s['n'])} | "
            f"{s['gen_tokens']:.1f} | {s['forward_passes']:.1f} | {s['wall_s']:.1f} | {s['errors']} | {s['cap_hits']} |"
        )
    lines.append("")
    base = results.get("baseline")
    for cfg in ("latent", "latent-early-exit"):
        if cfg not in results or base is None:
            continue
        c = paired(results[cfg], base)
        if c is None:
            continue
        lines += [
            f"**{cfg} vs baseline** (paired, n = {c['n']}): "
            f"both correct {c['both']}, only {cfg} {c['a_only']}, only baseline {c['b_only']}, neither {c['neither']}. "
            f"Accuracy difference {100 * c['acc_diff']:+.1f} points; exact two-sided McNemar p = {_p(c['p'])}.",
            "",
        ]
        if c["token_reduction"] is not None:
            direction = "fewer" if c["token_reduction"] >= 0 else "more"
            lines.append(
                f"- Generated tokens: {cfg} generated {abs(100 * c['token_reduction']):.1f}% {direction} "
                f"tokens than baseline (token reduction {100 * c['token_reduction']:+.1f}%)."
            )
        if c["forward_ratio"] is not None:
            lines.append(
                f"- Forward passes (counts prompt reads, latent steps and decoding): {cfg} used "
                f"{c['forward_ratio']:.2f}x the baseline's."
            )
        if c["acc_diff"] < 0:
            verdict = f"{cfg} is **less accurate** than the baseline on these problems"
        elif c["acc_diff"] > 0:
            verdict = f"{cfg} is more accurate than the baseline on these problems"
        else:
            verdict = f"{cfg} and the baseline have the same accuracy on these problems"
        sig = "statistically significant" if c["p"] < 0.05 else "**not** statistically significant"
        lines += [f"- Verdict: {verdict}; the difference is {sig} (alpha = 0.05).", ""]
    return lines


def build_summary(results_dir: Path, plan: Optional[dict]) -> str:
    n = plan.get("n") if plan else None
    lines = ["# Psiduck-AI eval summary", "", "Generated by `analyze.py` from `results/`. Do not edit by hand.", ""]
    if plan:
        s = plan.get("settings", {})
        lines += [
            f"- Model: `{s.get('model_name')}` ({s.get('quantization')}), greedy, seed {s.get('seed')}, "
            f"thinking disabled, max new tokens {s.get('max_new_tokens')}, latent steps/delegate {s.get('latent_steps')}.",
            f"- GSM8K: first N = {n} problems of the test split after a seed-42 shuffle (pre-registered in EVAL_PLAN.md).",
            "- Problems that raised an error count as incorrect.",
            "",
        ]
    lines += dataset_section(f"GSM8K (N = {n})", load_results(results_dir, "gsm8k", n), n or 0)
    aime = load_results(results_dir, "aime", None)
    if aime:
        lines += dataset_section("AIME 2024 + 2025 (60 problems)", aime, 60)
        lines.append("AIME results count only if both configs completed all 60 problems (pre-registered).")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def inject_readme(readme: Path, summary_md: str) -> None:
    text = readme.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        return
    body = summary_md.split("\n", 1)[1].strip()  # drop the "# ..." title line
    body = ("\n" + body).replace("\n## ", "\n### ").strip()
    new = f"{README_START}\n\n{body}\n\n{README_END}"
    pre = text.split(README_START)[0]
    post = text.split(README_END, 1)[1]
    readme.write_text(pre + new + post, encoding="utf-8")
